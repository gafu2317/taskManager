// 現在のプリセット（モジュールレベルで保持）
let currentPreset: PersonalityPresetId = 'flat';

export function setCurrentPreset(preset: string) {
  if (preset in eventDialogues) {
    currentPreset = preset as PersonalityPresetId;
  }
}

export function getEventDialogue(event: MascotEvent): string {
  const set = eventDialogues[currentPreset] ?? eventDialogues.flat;
  const list = set[event] ?? eventDialogues.flat[event];
  if (!list || list.length === 0) return '';
  return list[Math.floor(Math.random() * list.length)];
}

export function fireMascotEvent(event: MascotEvent) {
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('mascot-event', { detail: { event } }));
  }
}
