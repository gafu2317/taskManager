export function getDialogue(mood: MascotMood, preset: string = 'flat'): string {
  const set = dialogues[preset as PersonalityPresetId] ?? dialogues.flat;
  const list = set[mood] ?? dialogues.flat[mood];
  if (!list || list.length === 0) return '';
  return list[Math.floor(Math.random() * list.length)];
}

